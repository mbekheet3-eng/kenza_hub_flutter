import 'package:flutter/material.dart';
import 'package:kenza_hub_flutter/services/supabase_service.dart';
import 'package:kenza_hub_flutter/models/order.dart';

class Address {
  final String id;
  final String fullName;
  final String phone;
  final String street;
  final String city;
  final String governorate;
  final String postalCode;
  final String? apartment;
  bool isDefault;

  Address({
    required this.id,
    required this.fullName,
    required this.phone,
    required this.street,
    required this.city,
    required this.governorate,
    required this.postalCode,
    this.apartment,
    this.isDefault = false,
  });

  String get displayName => '$fullName - $street, $city';

  Map<String, dynamic> toJson() => {
    'id': id,
    'full_name': fullName,
    'phone': phone,
    'street': street,
    'city': city,
    'governorate': governorate,
    'postal_code': postalCode,
    'apartment': apartment,
    'is_default': isDefault,
  };

  factory Address.fromJson(Map<String, dynamic> json) => Address(
    id: json['id'] as String,
    fullName: json['full_name'] as String,
    phone: json['phone'] as String,
    street: json['street'] as String,
    city: json['city'] as String,
    governorate: json['governorate'] as String,
    postalCode: json['postal_code'] as String,
    apartment: json['apartment'] as String?,
    isDefault: json['is_default'] as bool? ?? false,
  );
}

class CheckoutProvider with ChangeNotifier {
  final SupabaseService _supabaseService = SupabaseService();

  // State
  List<Address> _addresses = [];
  Address? _selectedAddress;
  bool _isLoading = false;
  String? _error;
  
  // Checkout data
  String _paymentMethod = 'card'; // card, cash
  bool _agreedToTerms = false;
  bool _isProcessing = false;
  String? _orderId;

  // Getters
  List<Address> get addresses => _addresses;
  Address? get selectedAddress => _selectedAddress;
  bool get isLoading => _isLoading;
  String? get error => _error;
  String get paymentMethod => _paymentMethod;
  bool get agreedToTerms => _agreedToTerms;
  bool get isProcessing => _isProcessing;
  String? get orderId => _orderId;

  bool get canProceed =>
      _selectedAddress != null && _agreedToTerms && !_isProcessing;

  String get productId => _cartItems.isNotEmpty ? _cartItems.first.productId : '';
  List<CartItem> get cartItems => _cartItems;

  // Load addresses
  Future<void> loadAddresses() async {
    try {
      _isLoading = true;
      _error = null;
      notifyListeners();

      // For now, create sample address
      // In real app, fetch from Supabase
      _addresses = [
        Address(
          id: '1',
          fullName: 'أحمد محمد',
          phone: '+201001234567',
          street: 'شارع النيل',
          city: 'القاهرة',
          governorate: 'القاهرة',
          postalCode: '11511',
          isDefault: true,
        ),
      ];

      _selectedAddress = _addresses.first;
      _isLoading = false;
    } catch (e) {
      _isLoading = false;
      _error = 'خطأ في تحميل العناوين: ${e.toString()}';
      print('❌ Error loading addresses: $e');
    }
    notifyListeners();
  }

  // Add address
  void addAddress(Address address) {
    _addresses.add(address);
    if (_addresses.length == 1) {
      _selectedAddress = address;
    }
    notifyListeners();
  }

  // Select address
  void selectAddress(Address address) {
    _selectedAddress = address;
    notifyListeners();
  }

  // Update payment method
  void setPaymentMethod(String method) {
    if (_paymentMethod != method) {
      _paymentMethod = method;
      notifyListeners();
    }
  }

  // Toggle terms agreement
  void toggleTermsAgreement() {
    _agreedToTerms = !_agreedToTerms;
    notifyListeners();
  }

  // Process payment
  Future<bool> processPayment({
    required String buyerId,
    required List<Map<String, dynamic>> cartItems,
    required double totalAmount,
  }) async {
    try {
      if (_selectedAddress == null) {
        _error = 'يرجى اختيار عنوان التوصيل';
        notifyListeners();
        return false;
      }

      _isProcessing = true;
      _error = null;
      notifyListeners();

      // Create order in Supabase
      final order = Order(
        id: '', // Will be generated by Supabase
        productId: cartItems.isNotEmpty ? cartItems.first.productId : '',
        buyerId: buyerId,
        sellerId: '', // Will be set by seller
        amount: totalAmount,
        status: OrderStatus.pending,
        shippingAddress: _selectedAddress?.toJson() ?? '',
        trackingNumber: null,
        createdAt: DateTime.now(),
        updatedAt: DateTime.now(),
      );

      _orderId = await _supabaseService.createOrder(order);

      // Here you would integrate with payment gateway
      // For now, we'll simulate success for cash payment
      if (_paymentMethod == 'cash') {
        _isProcessing = false;
        print('✅ Order created with ID: $_orderId');
        return true;
      } else {
        // Integrate with Stripe/Tap/PayMob
        print('💳 Processing card payment for order: $_orderId');
        _isProcessing = false;
        return true;
      }
    } catch (e) {
      _isProcessing = false;
      _error = 'خطأ في معالجة الطلب: ${e.toString()}';
      print('❌ Payment processing error: $e');
    }
    notifyListeners();
    return false;
  }

  // Clear checkout state
  void reset() {
    _selectedAddress = null;
    _paymentMethod = 'card';
    _agreedToTerms = false;
    _isProcessing = false;
    _orderId = null;
    _error = null;
    notifyListeners();
  }
}
